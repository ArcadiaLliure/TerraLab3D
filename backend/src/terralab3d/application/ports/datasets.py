"""Ports d’adquisició, instal·lació i validació de datasets."""
from typing import Protocol
from terralab3d.domain.datasets.models import DatasetInstallation, DatasetManifest

class DatasetCatalogPort(Protocol):
    def manifests(self) -> tuple[DatasetManifest, ...]: ...
    def installation(self, dataset_id: str) -> DatasetInstallation: ...

class DatasetAcquisitionPort(Protocol):
    def acquire(self, manifest: DatasetManifest, operation_id: str) -> None: ...
    def cancel(self, operation_id: str) -> None: ...
